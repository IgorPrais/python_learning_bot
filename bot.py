def main():

    if not TOKEN:

        raise RuntimeError(
            "Не знайдено BOT_TOKEN.\n\n"
            "У PowerShell виконай:\n"
            '$env:BOT_TOKEN="ТВІЙ_НОВИЙ_ТОКЕН"\n\n'
            "Після цього запусти:\n"
            "python bot.py"
        )

    app = (
        Application
        .builder()
        .token(TOKEN)
        .build()
    )

    app.add_handler(
        CommandHandler(
            "start",
            start
        )
    )

    app.add_handler(
        CommandHandler(
            "help",
            help_command
        )
    )

    app.add_handler(
        CallbackQueryHandler(
            button_handler
        )
    )

    app.add_handler(
        MessageHandler(
            filters.TEXT
            & ~filters.COMMAND,
            text_handler
        )
    )

    app.add_error_handler(
        error_handler
    )

    print(
        "🐍 Великий навчальний бот Python запущено..."
    )

    app.run_polling()


if __name__ == "__main__":
    main()
