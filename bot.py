async def send_test_question(
    query,
    context,
    random_mode=False
):

    if random_mode:

        index = random.randrange(
            len(MCQ)
        )

    else:

        index = context.user_data.get(
            "test_index",
            0
        )

    if (
        not random_mode
        and index >= len(MCQ)
    ):

        user_id = query.from_user.id

        data = get_user_progress(user_id)

        correct = context.user_data.get(
            "test_session_correct",
            0
        )

        total = len(MCQ)

        percent = round(
            correct / total * 100
        )

        data["tests_completed"] += 1

        if percent > data["best_test"]:
            data["best_test"] = percent

        data["xp"] += correct * 10

        save_user_progress(
            user_id,
            data
        )

        await query.edit_message_text(

            "🏁 <b>ТЕСТ ЗАВЕРШЕНО!</b>\n\n"

            f"🎯 Результат: "
            f"<b>{correct}/{total}</b>\n\n"

            f"📊 Точність: "
            f"<b>{percent}%</b>\n\n"

            f"⭐ Отримано XP: "
            f"<b>+{correct * 10}</b>\n\n"

            f"🏆 Найкращий результат: "
            f"<b>{data['best_test']}%</b>",

            parse_mode="HTML",

            reply_markup=test_menu(),
        )

        return

    question, answers, correct_index = MCQ[index]

    context.user_data["test_current"] = index

    buttons = []

    for i, answer in enumerate(answers):

        buttons.append(
            [
                InlineKeyboardButton(
                    answer,
                    callback_data=f"testanswer:{i}"
                )
            ]
        )

    buttons.append(
        [
            InlineKeyboardButton(
                "🏠 Меню",
                callback_data="menu"
            )
        ]
    )

    question_number = (
        index + 1
        if not random_mode
        else "🎲"
    )

    await query.edit_message_text(

        f"🧠 <b>Питання "
        f"{question_number}/{len(MCQ)}</b>\n\n"
        f"{question}",

        parse_mode="HTML",

        reply_markup=InlineKeyboardMarkup(
            buttons
        ),
    )


