def lesson_keyboard(key, page):

    total = len(LESSONS[key]["pages"])

    buttons = []

    if page > 0:

        buttons.append(
            InlineKeyboardButton(
                "⬅️ Назад",
                callback_data=f"lesson:{key}:{page - 1}"
            )
        )

    if page < total - 1:

        buttons.append(
            InlineKeyboardButton(
                "➡️ Далі",
                callback_data=f"lesson:{key}:{page + 1}"
            )
        )

    rows = []

    if buttons:
        rows.append(buttons)

    if page == total - 1:

        rows.append(
            [
                InlineKeyboardButton(
                    "✅ Завершити тему",
                    callback_data=f"lesson_done:{key}"
                )
            ]
        )

    rows.append(
        [
            InlineKeyboardButton(
                "📚 До тем",
                callback_data="lessons"
            ),
            InlineKeyboardButton(
                "🏠 Меню",
                callback_data="menu"
            ),
        ]
    )

    return InlineKeyboardMarkup(rows)


async def show_lesson(query, key, page, user_id):

    pages = LESSONS[key]["pages"]

    page = max(
        0,
        min(page, len(pages) - 1)
    )

    progress = get_user_progress(user_id)

    if key not in progress["lessons_opened"]:

        progress["lessons_opened"].append(key)

        add_xp(user_id, 5)

    text = pages[page]

    header = (
        f"\n\n📖 <b>Сторінка "
        f"{page + 1} з {len(pages)}</b>"
    )

    await query.edit_message_text(
        text + header,
        parse_mode="HTML",
        reply_markup=lesson_keyboard(key, page),
    )


